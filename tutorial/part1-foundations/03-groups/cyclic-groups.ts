/**
 * Diffie-Hellman key exchange requires:
 * 1. A large prime p
 * 2. A generator g of (Z/pZ)*
 *
 * The security relies on the Discrete Log Problem being hard in this group.
 */
console.log("Diffie-Hellman Key Exchange Setup:\n");

// Small example (NOT cryptographically secure!)
const dhP = 23n;
const dhG = findPrimitiveRoot(dhP);

console.log(`  Prime p = ${dhP}`);
console.log(`  Generator g = ${dhG}`);
console.log(`  Group (Z/${dhP}Z)* has order ${dhP - 1n}\n`);

// Alice's private key
const alicePrivate = 6n;
const alicePublic = power_mod(dhG, alicePrivate, dhP);
console.log(`  Alice: private a = ${alicePrivate}, public A = g^a = ${dhG}^${alicePrivate} = ${alicePublic}`);

// Bob's private key
const bobPrivate = 15n;
const bobPublic = power_mod(dhG, bobPrivate, dhP);
console.log(`  Bob: private b = ${bobPrivate}, public B = g^b = ${dhG}^${bobPrivate} = ${bobPublic}`);

// Shared secret
const aliceComputes = power_mod(bobPublic, alicePrivate, dhP);
const bobComputes = power_mod(alicePublic, bobPrivate, dhP);

console.log(`\n  Alice computes: B^a = ${bobPublic}^${alicePrivate} = ${aliceComputes}`);
console.log(`  Bob computes: A^b = ${alicePublic}^${bobPrivate} = ${bobComputes}`);
console.log(`  Shared secret: ${aliceComputes}`);

console.log("\nThe security of DH depends on finding discrete logs being hard!");
console.log("For cryptographic use, p should be at least 2048 bits.");
