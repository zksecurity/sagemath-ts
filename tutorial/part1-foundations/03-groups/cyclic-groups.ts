// Example 8: Structure of (Z/nZ)* for Composite n
// =============================================================================
console.log("=== Example 8: (Z/nZ)* for Composite n ===\n");

/**
 * (Z/nZ)* is not always cyclic!
 * It's cyclic iff n = 1, 2, 4, p^k, or 2p^k for odd prime p.
 */
function isCyclic(n: bigint): boolean {
  if (n === 1n || n === 2n || n === 4n) return true;

  const factors = factor(n);
  const primeFactors = factors.filter(([p]) => p > 1n);

  // Check if n = p^k for odd prime p
  if (primeFactors.length === 1) {
    const [prime] = primeFactors[0]!;
    return prime !== 2n;  // p^k for odd p is cyclic
  }

  // Check if n = 2 * p^k for odd prime p
  if (primeFactors.length === 2) {
    const [[p1, e1], [p2, e2]] = primeFactors;
    if (p1 === 2n && e1 === 1n && p2! > 2n) return true;
    if (p2 === 2n && e2 === 1n && p1! > 2n) return true;
  }

  return false;
}

const testModuli = [5n, 8n, 9n, 10n, 12n, 15n, 16n, 18n, 25n];

console.log("Which (Z/nZ)* are cyclic?");
for (const mod of testModuli) {
  const phi = euler_phi(mod);
  const cyclic = isCyclic(mod);

  // Find maximum element order
  let maxOrder = 1n;
  for (let g = 1n; g < mod; g++) {
    if (gcd(g, mod) === 1n) {
      const ord = elementOrder(g, mod);
      if (ord > maxOrder) maxOrder = ord;
    }
  }

  console.log(`  (Z/${mod.toString().padStart(2)}Z)*: phi = ${phi.toString().padStart(2)}, max order = ${maxOrder.toString().padStart(2)}, cyclic? ${cyclic}`);
}

