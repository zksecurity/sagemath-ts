// =============================================================================
// Example 3: Computing Element Orders
// =============================================================================
console.log("=== Example 3: Computing Element Orders ===\n");

/**
 * The order of an element g is the smallest positive k such that g^k = e.
 * An element is a generator iff its order equals the group order.
 */
function elementOrder(g: bigint, n: bigint): bigint {
  // In (Z/nZ)*, compute order of g
  if (gcd(g, n) !== 1n) {
    throw new Error("g must be coprime to n");
  }

  const groupOrder = euler_phi(n);
  let order = 1n;
  let current = g % n;

  while (current !== 1n) {
    current = (current * g) % n;
    order++;
    if (order > groupOrder) {
      throw new Error("Element order exceeds group order");
    }
  }

  return order;
}

const modulus = 13n;
console.log(`Orders of elements in (Z/${modulus}Z)*:\n`);

const groupOrder = euler_phi(modulus);
console.log(`Group order = phi(${modulus}) = ${groupOrder}\n`);

for (let g = 1n; g < modulus; g++) {
  const ord = elementOrder(g, modulus);
  const divides = groupOrder % ord === 0n;
  const isGen = ord === groupOrder;
  console.log(`  ord(${g.toString().padStart(2)}) = ${ord.toString().padStart(2)}  (divides ${groupOrder}? ${divides}, generator? ${isGen})`);
}

console.log(`\nLagrange's Theorem: Element order always divides group order!`);

console.log();

