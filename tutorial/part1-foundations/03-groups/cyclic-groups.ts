// Example 6: Finding Primitive Roots
// =============================================================================
console.log("=== Example 6: Finding Primitive Roots (Generators of (Z/pZ)*) ===\n");

/**
 * Algorithm to find a primitive root modulo prime p:
 * 1. Compute p - 1 and its prime factorization
 * 2. For each candidate g, check if g^((p-1)/q) != 1 for each prime q | (p-1)
 */
function findPrimitiveRoot(p: bigint): bigint {
  if (p === 2n) return 1n;

  const pMinus1 = p - 1n;
  const factors = factor(pMinus1);
  const primeFactors = factors.filter(([f]) => f > 0n).map(([f]) => f);

  for (let g = 2n; g < p; g++) {
    let isPrimitive = true;

    for (const q of primeFactors) {
      const exp = pMinus1 / q;
      if (power_mod(g, exp, p) === 1n) {
        isPrimitive = false;
        break;
      }
    }

    if (isPrimitive) {
      return g;
    }
  }

  throw new Error("No primitive root found");
}

const prime = 23n;
console.log(`Finding a primitive root modulo ${prime}:\n`);

const pMinus1 = prime - 1n;
console.log(`  ${prime} - 1 = ${pMinus1}`);
const factors = factor(pMinus1);
console.log(`  Factorization: ${factors.map(([p, e]) => e === 1n ? `${p}` : `${p}^${e}`).join(' * ')}`);
console.log(`  Prime factors of ${pMinus1}: ${factors.filter(([f]) => f > 0n).map(([f]) => f).join(', ')}\n`);

const primitiveRoot = findPrimitiveRoot(prime);
console.log(`Smallest primitive root: ${primitiveRoot}`);

// Verify
