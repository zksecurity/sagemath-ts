/**
 * Simple Tonelli-Shanks square root
 */
function Fp_sqrt_simple(a: bigint, p: bigint): bigint | null {
  a = mod(a, p);
  if (a === 0n) return 0n;

  // Check if a is a quadratic residue using Euler's criterion
  const exp = (p - 1n) / 2n;
  if (mod_pow(a, exp, p) !== 1n) {
    return null;
  }

  // Special case: p = 3 mod 4
  if (mod(p, 4n) === 3n) {
    return mod_pow(a, (p + 1n) / 4n, p);
  }

  // Tonelli-Shanks algorithm
  let s = 0n;
  let q = p - 1n;
  while ((q & 1n) === 0n) {
    s++;
    q >>= 1n;
  }

  let z = 2n;
  while (mod_pow(z, exp, p) !== p - 1n) {
    z++;
  }

  let m = s;
  let c = mod_pow(z, q, p);
  let t = mod_pow(a, q, p);
  let r = mod_pow(a, (q + 1n) / 2n, p);

  while (true) {
    if (t === 1n) return r;

    let i = 1n;
    let temp = mod(t * t, p);
    while (temp !== 1n) {
      temp = mod(temp * temp, p);
      i++;
    }

    const b = mod_pow(c, 1n << (m - i - 1n), p);
    m = i;
    c = mod(b * b, p);
    t = mod(t * c, p);
    r = mod(r * b, p);
  }
}

function mod_pow(base: bigint, exp: bigint, p: bigint): bigint {
  if (exp === 0n) return 1n;
  let result = 1n;
  base = mod(base, p);
  while (exp > 0n) {
    if ((exp & 1n) === 1n) {
      result = mod(result * base, p);
    }
    exp >>= 1n;
    base = mod(base * base, p);
  }
  return result;
}

function gcd(a: bigint, b: bigint): bigint {
  a = a < 0n ? -a : a;
  b = b < 0n ? -b : b;
  while (b !== 0n) {
    const t = b;
    b = a % b;
    a = t;
  }
  return a;
}

function mod(a: bigint, p: bigint): bigint {
  const r = a % p;
  return r < 0n ? r + p : r;
}
