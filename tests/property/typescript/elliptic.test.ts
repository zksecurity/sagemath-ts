/**
 * Parsed PARI/GP test result
 */
interface PariTestResult {
  testNumber: number;
  operation: string;
  comments: string[];
  result: string;
}

/**
 * Parse PARI/GP output file into structured test results
 */
function parsePariOutput(content: string): PariTestResult[] {
  const results: PariTestResult[] = [];
  const lines = content.split('\n');

  let currentOperation = '';
  let currentComments: string[] = [];
  let testNumber = 0;

  for (const line of lines) {
    const trimmed = line.trim();

    if (trimmed.startsWith('# ') && !trimmed.match(/^# (P|Q|G|n |m |k |order|degree|card|e\(|dlog|-?\d|O$)/i)) {
      // This is an operation line (main description)
      currentOperation = trimmed.substring(2);
      currentComments = [];
    } else if (trimmed.startsWith('# ')) {
      // This is a comment/context line
      currentComments.push(trimmed.substring(2));
    } else if (trimmed.startsWith('RESULT: ')) {
      // This is a result line
      testNumber++;
      const result = trimmed.substring(8);
      results.push({
        testNumber,
        operation: currentOperation,
        comments: currentComments,
        result,
      });
      currentOperation = '';
      currentComments = [];
    }
  }

  return results;
}

/**
 * Parse a point string from PARI output
 * Format: "[x, y]" or "INFINITY"
 */
function parsePoint(s: string): EllipticPointFp {
  if (s === 'INFINITY') {
    return ellinf();
  }

  const match = s.match(/\[(-?\d+), (-?\d+)\]/);
  if (!match) {
    throw new Error(`Cannot parse point: ${s}`);
  }

  return ellpoint(BigInt(match[1]!), BigInt(match[2]!));
}

/**
 * Format a point to match PARI output
 */
function formatPoint(P: EllipticPointFp): string {
  if (ell_is_inf(P)) {
    return 'INFINITY';
  }
  return `[${P.x}, ${P.y}]`;
}

/**
 * Parse curve info from PARI output
 * Format: "a1=0, a2=0, a3=0, a4=1, a6=2, disc=..., j=..."
 */
interface CurveInfo {
  a1: bigint;
  a2: bigint;
  a3: bigint;
  a4: bigint;
  a6: bigint;
  disc: bigint;
  j: bigint;
}

function parseCurveInfo(s: string): CurveInfo {
  const parts = s.split(', ');
  const values: Record<string, bigint> = {};

  for (const part of parts) {
    const [key, value] = part.split('=');
    values[key!] = BigInt(value!);
  }

  return {
    a1: values['a1']!,
    a2: values['a2']!,
    a3: values['a3']!,
    a4: values['a4']!,
    a6: values['a6']!,
    disc: values['disc']!,
    j: values['j']!,
  };
}

/**
 * Format curve info to match PARI output
 */
function formatCurveInfo(E: ReturnType<typeof ellinit>): string {
  return `a1=${E.a1}, a2=${E.a2}, a3=${E.a3}, a4=${E.a4}, a6=${E.a6}, disc=${E.disc}, j=${E.j}`;
}

/**
 * Parse ellgroup result
 * Format: "[28]" or "[14, 2]" or "[]"
 */
function parseGroup(s: string): bigint[] {
  const match = s.match(/\[([^\]]*)\]/);
  if (!match) {
    throw new Error(`Cannot parse group: ${s}`);
  }

  if (match[1] === '') {
    return [];
  }

  return match[1]!.split(', ').map((x) => BigInt(x.trim()));
}

/**
 * Format group structure to match PARI output
 */
function formatGroup(group: bigint[]): string {
  return `[${group.join(', ')}]`;
}

/**
 * Parse polynomial from PARI output
 * Format: "[coeff0, coeff1, ..., coeffN]" (from lowest to highest degree)
 */
function parsePoly(s: string): bigint[] {
  if (s === '[]') return [];

  const match = s.match(/\[([^\]]*)\]/);
  if (!match) {
    throw new Error(`Cannot parse polynomial: ${s}`);
  }

  if (match[1] === '') {
    return [];
  }

  return match[1]!.split(', ').map((x) => BigInt(x.trim()));
}

/**
 * Format polynomial to match PARI output
 */
function formatPoly(coeffs: bigint[]): string {
  if (coeffs.length === 0) return '[]';
  return `[${coeffs.join(', ')}]`;
}

/**
 * Normalize polynomial by removing trailing zeros
 */
function normalizePoly(coeffs: bigint[]): bigint[] {
  let len = coeffs.length;
  while (len > 0 && coeffs[len - 1] === 0n) {
    len--;
  }
  return coeffs.slice(0, len);
}

/**
 * Wrapper functions to use the correct API from parigp-ts
 */
function FpE_add_wrapped(E: EllipticCurveFp, P: EllipticPointFp, Q: EllipticPointFp): EllipticPointFp {
  return FpE_add(P, Q, E.a4, E.p);
}

function FpE_neg_wrapped(E: EllipticCurveFp, P: EllipticPointFp): EllipticPointFp {
  return FpE_neg(P, E.p);
}

function FpE_mul_wrapped(E: EllipticCurveFp, P: EllipticPointFp, n: bigint): EllipticPointFp {
  return FpE_mul(P, n, E.a4, E.p);
}

