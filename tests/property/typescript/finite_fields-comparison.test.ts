/**
 * Parsed SageMath test result
 */
interface SageTestResult {
  operation: string;
  result: string;
}

/**
 * Parse SageMath output file into structured test results
 */
function parseSageOutput(content: string): SageTestResult[] {
  const results: SageTestResult[] = [];
  const lines = content.split('\n');

  let currentOperation = '';

  for (const line of lines) {
    if (line.startsWith('# ') && !line.startsWith('# ==')) {
      // This is an operation description
      currentOperation = line.substring(2);
    } else if (line.startsWith('RESULT: ')) {
      // This is a result line
      const result = line.substring(8);
      results.push({
        operation: currentOperation,
        result,
      });
    }
  }

  return results;
}

/**
 * Find result for a specific operation
 */
function findResult(results: SageTestResult[], operation: string): string | undefined {
  const found = results.find((r) => r.operation === operation);
  return found?.result;
}

