describe('matkermod: composite moduli, verified by brute force', () => {
  it('every returned basis vector is in the kernel (n = 12,36,100,360)', () => {
    const rnd = mkrnd(12345n);
    let checked = 0;
    for (const n of [12n, 36n, 100n, 360n]) {
      for (let m = 1; m <= 4; m++)
        for (let k = 1; k <= 4; k++) {
          for (let c = 0; c < 25; c++) {
            const rows = randMat(rnd, m, k, n);
            const { ker } = matkermod(zm_from_rows(rows), n);
            for (const v of ker)
              for (const r of rows) {
                let s = 0n;
                for (let j = 0; j < k; j++) s += r[j]! * v[j]!;
                expect(((s % n) + n) % n).toBe(0n);
              }
            checked++;
          }
        }
    }
    expect(checked).toBe(1600);
  });

  it('the returned basis spans exactly the full kernel (exhaustive, small n)', () => {
    const rnd = mkrnd(777n);
    let checked = 0;
    for (const n of [4n, 6n, 8n, 9n, 12n]) {
      for (let m = 1; m <= 3; m++)
        for (let k = 1; k <= 3; k++) {
          for (let c = 0; c < 10; c++) {
            const rows = randMat(rnd, m, k, n);
            const { ker } = matkermod(zm_from_rows(rows), n);
            const brute = bruteKernel(rows, n);
            const sp = span(ker, n, k);
            expect(sp.size).toBe(brute.size);
            for (const s of sp) expect(brute.has(s)).toBe(true);
            checked++;
          }
        }
    }
    expect(checked).toBe(450);
  });

  it('matimagemod spans the same submodule as the columns of A, and A*U == H', () => {
    const rnd = mkrnd(31337n);
    for (const n of [4n, 6n, 12n]) {
      for (let m = 1; m <= 3; m++)
        for (let k = 1; k <= 3; k++)
          for (let c = 0; c < 8; c++) {
            const rows = randMat(rnd, m, k, n);
            const A = zm_from_rows(rows);
            const { im, U } = matimagemod(A, n, true);
            const s1 = span(A, n, m);
            const s2 = span(im, n, m);
            expect(s2.size).toBe(s1.size);
            for (const x of s2) expect(s1.has(x)).toBe(true);
            for (let j = 0; j < U!.length; j++)
              for (let i = 0; i < m; i++) {
                let s = 0n;
                for (let t = 0; t < k; t++) s += rows[i]![t]! * U![j]![t]!;
                expect(((s % n) + n) % n).toBe(((im[j]![i]! % n) + n) % n);
              }
          }
    }
  });

  it('matdetmod agrees with the exact determinant reduced mod d', () => {
    const rnd = mkrnd(999n);
    for (const d of [36n, 27n, 100n, 360n])
      for (let n = 1; n <= 4; n++)
        for (let c = 0; c < 25; c++) {
          const rows = randMat(rnd, n, n, 50n);
          expect(matdetmod(zm_from_rows(rows), d)).toBe(((exactDet(rows) % d) + d) % d);
        }
  });

  it('matinvmod returns a genuine left inverse whenever it succeeds', () => {
    const rnd = mkrnd(4242n);
    let inverted = 0;
    for (const d of [1800n, 31n, 36n])
      for (let m = 1; m <= 4; m++)
        for (let n2 = 1; n2 <= 4; n2++)
          for (let c = 0; c < 20; c++) {
            const rows = randMat(rnd, m, n2, d);
            let U: ZM;
            try {
              U = matinvmod(zm_from_rows(rows), d);
            } catch (e) {
              expect(e).toBeInstanceOf(PariInvError);
              continue;
            }
            inverted++;
            const Urows = zm_to_rows(U);
            for (let i = 0; i < Urows.length; i++)
              for (let j = 0; j < n2; j++) {
                let s = 0n;
                for (let t = 0; t < m; t++) s += Urows[i]![t]! * rows[t]![j]!;
                expect(((s % d) + d) % d).toBe(i === j ? 1n : 0n);
              }
          }
    expect(inverted).toBeGreaterThan(100);
  });
});

describe('matkermod: edge cases and errors', () => {
  it('d = 1 (zero ring) gives an empty matrix', () => {
    expect(
      matkermod(
        R([
          [1, 2],
          [3, 4],
        ]),
        1n
      ).ker
    ).toEqual([]);
    expect(
      matimagemod(
        R([
          [1, 2],
          [3, 4],
        ]),
        1n
      ).im
    ).toEqual([]);
    expect(matdetmod(R([[3]]), 1n)).toBe(0n);
  });

  it('d <= 0 is a domain error', () => {
    expect(() => matkermod(R([[1]]), 0n)).toThrow(PariDomainError);
    expect(() => matimagemod(R([[1]]), -1n)).toThrow(PariDomainError);
    expect(() => matdetmod(R([[1]]), 0n)).toThrow(PariDomainError);
  });

  it('matkermod also returns the image when asked', () => {
    const A = R([
      [1, 2, 3],
      [5, 1, 4],
    ]);
    const { ker, im } = matkermod(A, 6n, true);
    expect(rowsOf(ker)).toEqual([
      [2, 1],
      [2, 1],
      [0, 3],
    ]);
    expect(rowsOf(im!)).toEqual(rowsOf(matimagemod(A, 6n).im));
  });

  it('matkermod_basis returns kernel vectors as rows', () => {
    const basis = matkermod_basis(
      [
        [1n, 2n, 3n],
        [5n, 1n, 4n],
      ],
      6n
    );
    expect(basis).toEqual([
      [2n, 2n, 0n],
      [1n, 1n, 3n],
    ]);
  });

  it('tall matrices take the transposed-image shortcut and still agree', () => {
    // m > 2n triggers the `matimagemod(A^T)` pre-reduction in matkermod.
    const rnd = mkrnd(24680n);
    for (const n of [12n, 36n]) {
      for (let k = 1; k <= 2; k++) {
        for (let c = 0; c < 15; c++) {
          const rows = randMat(rnd, 5 * k, k, n);
          const { ker } = matkermod(zm_from_rows(rows), n);
          const brute = bruteKernel(rows, n);
          const sp = span(ker, n, k);
          expect(sp.size).toBe(brute.size);
          for (const s of sp) expect(brute.has(s)).toBe(true);
        }
      }
    }
  });
});
