/**
 * @module matkermod.test
 * @description Tests for linear algebra over Z/dZ (Howell form).
 *
 * Golden values are taken verbatim from PARI's own regression suite
 * `reference/pari/src/test/in/bbhnf` + `reference/pari/src/test/32/bbhnf`
 * and from the documentation examples in
 * `reference/pari/src/functions/linear_algebra/{matkermod,matimagemod,matdetmod}`.
 *
 * NOTE: the `matdetmod` doc example claims `matdetmod([4,2,3;4,5,6;7,8,9],27) == 9`,
 * but the actual determinant is -9, i.e. 18 mod 27, and PARI's own test output
 * (`test/32/bbhnf`, line 240) records 18. We assert 18 (PARI's real behaviour).
 */

import { describe, expect, it } from 'bun:test';
