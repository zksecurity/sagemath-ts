/** PARI `ab_isreduced` (`Qfb.c:507-516`), used as an independent oracle here */
function isReducedIndefinite(q: QfbT, rd: bigint): boolean {
  const abs = (x: bigint): bigint => (x < 0n ? -x : x);
  if (q.b <= 0n || abs(q.b) > abs(rd)) return false;
  const t = rd - abs(2n * q.a);
  return t < 0n ? abs(q.b) >= abs(t) : abs(q.b) > abs(t);
}

/** definite reduced: |b| <= a <= c, and b >= 0 if |b| == a or a == c */
function isReducedDefinite(q: QfbT): boolean {
  const abs = (x: bigint): bigint => (x < 0n ? -x : x);
  if (!(abs(q.b) <= q.a && q.a <= q.c)) return false;
  if ((abs(q.b) === q.a || q.a === q.c) && q.b < 0n) return false;
  return true;
}

const Qv = (q: QfbT, x: bigint, y: bigint): bigint => q.a * x * x + q.b * x * y + q.c * y * y;

