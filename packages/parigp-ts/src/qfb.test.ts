/** exact fraction of a decimal literal, for comparing t_REALs exactly */
const decFrac = (s: string): [bigint, bigint] => {
  let t = s.trim().replace(/\s+/g, '');
  let sign = 1n;
  if (t[0] === '-') {
    sign = -1n;
    t = t.slice(1);
  } else if (t[0] === '+') t = t.slice(1);
  let exp = 0;
  const m = t.match(/[eE]([-+]?\d+)$/);
  if (m) {
    exp = Number.parseInt(m[1]!, 10);
    t = t.slice(0, m.index);
  }
  const dot = t.indexOf('.');
  let digits = t;
  if (dot >= 0) {
    digits = t.slice(0, dot) + t.slice(dot + 1);
    exp -= t.length - dot - 1;
  }
  let num = sign * BigInt(digits === '' ? '0' : digits);
  let den = 1n;
  if (exp >= 0) num *= 10n ** BigInt(exp);
  else den = 10n ** BigInt(-exp);
  return [num, den];
};

/** |x - g| / max(1, |g|), exactly, as a double */
const reldiff = (x: MpReal, g: string): number => {
  const [gn, gd] = decFrac(g);
  const [xn, xd] = mpreal_to_frac(x);
  const dn = xn * gd - gn * xd;
  const dd = xd * gd;
  if (dn === 0n) return 0;
  const abs = Math.abs(Number((dn * 10n ** 60n) / dd) / 1e60);
  const gv = gn === 0n ? 0 : Math.abs(Number((gn * 10n ** 60n) / gd) / 1e60);
  return abs / Math.max(1, gv);
};

/** `x` as a double (only used for the mod-R bookkeeping) */
const rnum = (x: MpReal): number => {
  const [n, d] = mpreal_to_frac(x);
  return Number((n * 10n ** 40n) / d) / 1e40;
};

/** GP's printed form of the exact fraction `num/den` at `n` significant digits */
const fmtFrac = (num: bigint, den: bigint, n: number): string => {
  if (num === 0n) return '0';
  const neg = num < 0n;
  const a = neg ? -num : num;
  const P = 400;
  const v = (a * 10n ** BigInt(P)) / den;
  const s = v.toString();
  let exp10 = s.length - 1 - P;
  let head = BigInt(s.slice(0, n));
  if (s.charCodeAt(n) - 48 >= 5) {
    head += 1n;
    if (head.toString().length > n) {
      head /= 10n;
      exp10 += 1;
    }
  }
  const d = head.toString();
  const sg = neg ? '-' : '';
  if (exp10 >= 0 && exp10 < n) return `${sg}${d.slice(0, exp10 + 1)}.${d.slice(exp10 + 1)}`;
  if (exp10 < 0 && exp10 >= -8) return `${sg}0.${'0'.repeat(-exp10 - 1)}${d}`;
  return `${sg}${d[0]}.${d.slice(1)}E${exp10}`;
};
/** GP's printed form of a t_REAL at `n` significant digits */
const gpstr = (x: MpReal, n: number): string => {
  /* PARI prints a real zero as `0.E-k` with k = (long)(-expo * LOG10_2) */
  if (x.s === 0) return `0.E${x.e < 0 ? '-' : ''}${Math.trunc(Math.abs(x.e) * Math.log10(2))}`;
  const [num, den] = mpreal_to_frac(x);
  return fmtFrac(num, den, n);
};
/** a decimal literal rounded to `n` significant digits, GP style */
const roundDec = (s: string, n: number): string => {
  const [num, den] = decFrac(s);
  return fmtFrac(num, den, n);
};
/**
 * Assert that `x` is PARI's value `g`: identical to 36 significant digits, and
 * within one unit in the last place of a 128-bit t_REAL (5e-38 relative) of
 * PARI's full 38-digit literal.  PARI's mp kernel and ours round differently
 * in the last bit (see the DEVIATION note in qfb.ts), so the 38th printed
 * digit can differ by one; nothing above that can.
 */
const expectDist = (x: MpReal, g: string): void => {
  expect(gpstr(x, 36)).toBe(roundDec(g, 36));
  expect(`${g}: ${reldiff(x, g) < 5e-38}`).toBe(`${g}: true`);
};
/** |x - y| / max(1,|y|) for two t_REALs, exactly */
const reldiffR = (x: MpReal, y: MpReal): number => reldiff(x, fmtFrac(...mpreal_to_frac(y), 80));

