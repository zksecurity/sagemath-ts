describe('FpX helpers used by ffinit', () => {
  it('FpX_is_irred agrees with brute force over small fields', () => {
    for (const p of [2n, 3n, 5n]) {
      const P = Number(p);
      for (let d = 1; d <= 3; d++) {
        const total = P ** d;
        for (let code = 0; code < total; code++) {
          const f = pol_xn(d);
          let c = code;
          for (let i = 0; i < d; i++) {
            f[i] = BigInt(c % P);
            c = Math.floor(c / P);
          }
          // brute force: irreducible iff no monic factor of degree 1..floor(d/2)
          let red = false;
          for (let e = 1; e <= Math.floor(d / 2) && !red; e++) {
            const tot = P ** e;
            for (let code2 = 0; code2 < tot && !red; code2++) {
              const g = pol_xn(e);
              let c2 = code2;
              for (let i = 0; i < e; i++) {
                g[i] = BigInt(c2 % P);
                c2 = Math.floor(c2 / P);
              }
              if (FpX_rem(f, g, p).length === 0) red = true;
            }
          }
          expect(FpX_is_irred(f, p)).toBe(!red);
        }
      }
    }
  });

  it('FpX_gcd is consistent with divisibility', () => {
    const p = 7n;
    const a: FpX = [1n, 2n, 1n]; // (x+1)^2
    const b: FpX = [6n, 0n, 1n]; // x^2-1 = (x-1)(x+1)
    expect(FpX_gcd(a, b, p)).toEqual([1n, 1n]); // x+1
  });
});
