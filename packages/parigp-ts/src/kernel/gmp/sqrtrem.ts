const u64 = (n: bigint) => BigInt.asUintN(64, n),
  i64 = (n: bigint) => BigInt.asIntN(64, n);
function mpn_sqrtrem1(a: bigint): [bigint, bigint] {
  let x = 0x100n | BigInt(invsqrttab[Number(a >> 55n) - 128]!);
  const a1 = a >> 31n;
  let t = i64(0x2000000000000n - 0x30000n - a1 * x * x) >> 16n;
  x = u64((x << 16n) + (i64(x * t) >> 18n));
  const t2 = u64(x * (a >> 24n));
  t = t2 >> 25n;
  t = i64((a << 14n) - t * t - 0x10000000000n) >> 24n;
  x = u64(t2 + (i64(x * t) >> 15n)) >> 32n;
  let square = x * x;
  if (square + 2n * x <= a - 1n) {
    square += 2n * x + 1n;
    x++;
  }
  return [x, a - square];
}
function mpn_sqrtrem2(a: bigint): [bigint, bigint] {
  const [top, rem] = mpn_sqrtrem1(a >> 64n),
    low = u64(a);
  const numerator = (rem << 31n) + (low >> 33n);
  let q = numerator / top;
  q -= q >> 32n;
  const u = numerator - q * top;
  let s = (top << 32n) | q,
    r = (u << 33n) + (low & ((1n << 33n) - 1n)) - q * q;
  if (r < 0n) {
    r += 2n * s - 1n;
    s--;
  }
  return [s, r];
}
function mpn_dc_sqrtrem(a: bigint, n: number): [bigint, bigint] {
  if (n === 1) return mpn_sqrtrem2(a);
  const l = Math.floor(n / 2),
    h = n - l,
    shift = BigInt(l * 64),
    mask = (1n << shift) - 1n;
  const [top, rem] = mpn_dc_sqrtrem(a >> (2n * shift), h);
  const numerator = (rem << shift) + ((a >> shift) & mask),
    q = (numerator / top) >> 1n;
  let s = (top << shift) + q,
    r = ((numerator - 2n * top * q) << shift) + (a & mask) - q * q;
  if (r < 0n) {
    r += 2n * s - 1n;
    s--;
  }
  return [s, r];
}
export function mpn_sqrtrem(a: bigint): [bigint, bigint] {
  if (!a) return [0n, 0n];
  if (a < 0n) throw new RangeError('sqrtrem requires a nonnegative integer');
  const bits = a.toString(2).length,
    words = Math.ceil(bits / 64),
    c = Math.floor((words * 64 - bits) / 2);
  const k = BigInt(c + (words > 2 && words % 2 ? 32 : 0));
  const normalized = a << (2n * k);
  const [s, r] =
    words === 1
      ? mpn_sqrtrem1(normalized)
      : words === 2
        ? mpn_sqrtrem2(normalized)
        : mpn_dc_sqrtrem(normalized, Math.ceil(words / 2));
  const tail = s & ((1n << k) - 1n);
  return [s >> k, (r + 2n * s * tail - tail * tail) >> (2n * k)];
}
